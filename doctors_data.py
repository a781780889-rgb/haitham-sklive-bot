def get_doctors_for_hospital(hospital_name: str) -> list:
    """
    إرجاع قائمة أطباء المستشفى.
    يجرب الاسم المباشر أولاً ثم الأسماء البديلة.
    """
    doctors = DOCTORS_DATA.get(hospital_name)
    if doctors:
        return doctors
    # جرب الأسماء البديلة
    canonical = HOSPITAL_ALIASES.get(hospital_name)
    if canonical:
        return DOCTORS_DATA.get(canonical, [])
    # بحث جزئي
    for key, docs in DOCTORS_DATA.items():
        if hospital_name in key or key in hospital_name:
            return docs
    return []


def count_doctors() -> dict:
    """إحصائيات عدد الأطباء."""
    total = sum(len(v) for v in DOCTORS_DATA.values())
    return {
        "total": total,
        "hospitals_count": len(DOCTORS_DATA),
    }


