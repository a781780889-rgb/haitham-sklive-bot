def get_hospitals_for_city(city: str) -> dict:
    """
    إرجاع قاموس المستشفيات لمدينة معينة.
    مثال: {"حكومي": [...], "خاص": [...], "مجمعات": [...]}
    """
    return KSA_HOSPITALS.get(city, {"حكومي": [], "خاص": [], "مجمعات": []})


def get_all_hospitals_for_city_flat(city: str) -> list:
    """
    إرجاع قائمة مسطحة بجميع مستشفيات المدينة (حكومي + خاص + مجمعات).
    """
    data = get_hospitals_for_city(city)
    result = []
    for category in ["حكومي", "خاص", "مجمعات"]:
        result.extend(data.get(category, []))
    return result


def get_city_region(city: str) -> str:
    """إرجاع اسم المنطقة الإدارية للمدينة."""
    return KSA_HOSPITALS.get(city, {}).get("region", "غير محدد")


def get_cities_by_region(region: str) -> list:
    """إرجاع قائمة المدن في منطقة إدارية معينة."""
    return KSA_REGIONS.get(region, [])


def get_all_hospitals_flat() -> list:
    """
    إرجاع قائمة بجميع المستشفيات في المملكة (dict لكل مستشفى).
    مفيد لتهيئة قاعدة البيانات.
    """
    result = []
    for city, data in KSA_HOSPITALS.items():
        region = data.get("region", "")
        for category in ["حكومي", "خاص", "مجمعات"]:
            for h_name in data.get(category, []):
                result.append({
                    "name": h_name,
                    "city": city,
                    "region": region,
                    "type": category,
                })
    return result


def count_hospitals() -> dict:
    """إحصائيات عدد المستشفيات."""
    total = 0
    by_type = {"حكومي": 0, "خاص": 0, "مجمعات": 0}
    by_region = {}
    for city, data in KSA_HOSPITALS.items():
        region = data.get("region", "أخرى")
        if region not in by_region:
            by_region[region] = 0
        for cat in ["حكومي", "خاص", "مجمعات"]:
            count = len(data.get(cat, []))
            total += count
            by_type[cat] += count
            by_region[region] += count
    return {
        "total": total,
        "by_type": by_type,
        "by_region": by_region,
        "cities_count": len(KSA_HOSPITALS),
    }


